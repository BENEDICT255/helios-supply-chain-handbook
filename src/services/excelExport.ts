import * as XLSX from 'xlsx';
import type { DbDeliveryTimeline, DbProcurementStep } from '@/types/database';

/**
 * Mitigates Excel formula injection by prepending a single quote
 * if a string value starts with =, +, -, or @.
 */

const APPROVED_DEPARTMENTS = [
  'Information Technology',
  'Administration',
  'Network Operations',
  'Fleet',
  'Health, Safety and Environment',
  'Professional Services',
];

const APPROVED_STATUSES = ['published', 'draft'];

export function sanitizeExcelValue(value: unknown): string | number | boolean {
  if (value === null || value === undefined) return '';
  if (typeof value === 'number' || typeof value === 'boolean') return value;

  const str = String(value).trim();
  if (/^[=+\-@]/.test(str)) {
    return `'${str}`;
  }
  return str;
}

/**
 * Builds the 4-sheet workbook structure for Helios Towers Supply Chain Handbook.
 */
export function createHandbookWorkbook(params: {
  deliveryTimelines?: DbDeliveryTimeline[];
  procurementSteps?: DbProcurementStep[];
  generatedBy?: string;
  isTemplate?: boolean;
}): XLSX.WorkBook {
  const {
    deliveryTimelines = [],
    procurementSteps = [],
    generatedBy = 'System Admin',
    isTemplate = false,
  } = params;

  const workbook = XLSX.utils.book_new();
  const currentDate = new Date().toISOString().split('T')[0];

  // ----------------------------------------------------
  // 1. INSTRUCTIONS SHEET
  // ----------------------------------------------------
  const instructionsData = [
    ['HELIOS TOWERS SUPPLY CHAIN HANDBOOK — BULK EDITING INSTRUCTIONS'],
    [''],
    ['Workbook generated at:', currentDate],
    ['Workbook generated by:', generatedBy],
    ['Application version:', '1.0'],
    [''],
    ['IMPORTANT RULES FOR ADMINISTRATORS:'],
    ['1. The database remains the source of truth at all times.'],
    ['2. DO NOT change or rename column headings.'],
    ['3. DO NOT modify existing Record IDs (Column A). Existing records require their ID.'],
    ['4. For NEW records, leave the Record ID cell blank.'],
    ['5. Required fields must not be left empty (Item, Lead Time, Step Title, Description, etc.).'],
    ['6. Removing a row from this spreadsheet does NOT automatically delete it from the database.'],
    ['   Deletions must be explicitly confirmed during the import preview in the admin portal.'],
    ['7. Status must be either "published" or "draft".'],
    ['8. Department must be one of the approved values listed on the Reference Data sheet.'],
    ['9. Step Number and Display Order must be whole numbers.'],
    ['10. Formula cells (=, +, -, @) are strictly prohibited for security reasons.'],
    ['11. Upload the completed workbook through the protected Admin Portal.'],
    ['12. A backup snapshot is automatically created before any import is applied.'],
  ];

  const instructionsSheet = XLSX.utils.aoa_to_sheet(instructionsData);
  instructionsSheet['!cols'] = [{ wch: 45 }, { wch: 55 }];
  XLSX.utils.book_append_sheet(workbook, instructionsSheet, 'Instructions');

  // ----------------------------------------------------
  // 2. DELIVERY TIMELINES SHEET
  // ----------------------------------------------------
  const deliveryHeaders = [
    'Record ID',
    'Department',
    'Category',
    'Item or Service',
    'Estimated Lead Time',
    'Requirements',
    'Notes',
    'Status',
    'Display Order',
  ];

  const deliveryRows = isTemplate
    ? []
    : deliveryTimelines.map((item) => [
        sanitizeExcelValue(item.id),
        sanitizeExcelValue(item.department),
        sanitizeExcelValue(item.category),
        sanitizeExcelValue(item.item),
        sanitizeExcelValue(item.estimated_lead_time),
        sanitizeExcelValue(item.requirements || ''),
        sanitizeExcelValue(item.notes || ''),
        sanitizeExcelValue(item.status),
        item.display_order ?? 0,
      ]);

  const deliverySheet = XLSX.utils.aoa_to_sheet([deliveryHeaders, ...deliveryRows]);
  deliverySheet['!cols'] = [
    { wch: 38 }, // Record ID
    { wch: 30 }, // Department
    { wch: 30 }, // Category
    { wch: 30 }, // Item
    { wch: 20 }, // Lead Time
    { wch: 40 }, // Requirements
    { wch: 40 }, // Notes
    { wch: 15 }, // Status
    { wch: 15 }, // Display Order
  ];
  XLSX.utils.book_append_sheet(workbook, deliverySheet, 'Delivery Timelines');

  // ----------------------------------------------------
  // 3. PROCUREMENT PROCESS SHEET
  // ----------------------------------------------------
  const procurementHeaders = [
    'Record ID',
    'Step Number',
    'Title',
    'Description',
    'Responsible Party',
    'Expected Duration',
    'Notes',
    'Status',
    'Display Order',
  ];

  const procurementRows = isTemplate
    ? []
    : procurementSteps.map((step) => [
        sanitizeExcelValue(step.id),
        step.step_number ?? 1,
        sanitizeExcelValue(step.title),
        sanitizeExcelValue(step.description),
        sanitizeExcelValue(step.responsible_party || ''),
        sanitizeExcelValue(step.expected_duration || ''),
        sanitizeExcelValue(step.notes || ''),
        sanitizeExcelValue(step.status),
        step.display_order ?? 0,
      ]);

  const procurementSheet = XLSX.utils.aoa_to_sheet([procurementHeaders, ...procurementRows]);
  procurementSheet['!cols'] = [
    { wch: 38 }, // Record ID
    { wch: 15 }, // Step Number
    { wch: 30 }, // Title
    { wch: 50 }, // Description
    { wch: 30 }, // Responsible Party
    { wch: 20 }, // Expected Duration
    { wch: 40 }, // Notes
    { wch: 15 }, // Status
    { wch: 15 }, // Display Order
  ];
  XLSX.utils.book_append_sheet(workbook, procurementSheet, 'Procurement Process');

  // ----------------------------------------------------
  // 4. REFERENCE DATA SHEET
  // ----------------------------------------------------
  const refHeaders = ['Approved Departments', 'Publication Statuses', 'Workbook Version'];
  const maxRefRows = Math.max(APPROVED_DEPARTMENTS.length, APPROVED_STATUSES.length);
  const refRows: (string | number)[][] = [];

  for (let i = 0; i < maxRefRows; i++) {
    refRows.push([
      APPROVED_DEPARTMENTS[i] || '',
      APPROVED_STATUSES[i] || '',
      i === 0 ? '1.0' : '',
    ]);
  }

  const referenceSheet = XLSX.utils.aoa_to_sheet([refHeaders, ...refRows]);
  referenceSheet['!cols'] = [{ wch: 35 }, { wch: 25 }, { wch: 20 }];
  XLSX.utils.book_append_sheet(workbook, referenceSheet, 'Reference Data');

  return workbook;
}

/**
 * Returns a Buffer of the generated Excel workbook.
 */
export function exportHandbookToBuffer(params: {
  deliveryTimelines?: DbDeliveryTimeline[];
  procurementSteps?: DbProcurementStep[];
  generatedBy?: string;
  isTemplate?: boolean;
}): Buffer {
  const workbook = createHandbookWorkbook(params);
  return XLSX.write(workbook, { type: 'buffer', bookType: 'xlsx' });
}
